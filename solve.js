// Fast reimplementation of makefun-site 1.0.0's build(input), written from its README.md and
// its code (baselines/makefun-site/vendor/makefun-site/) line by line. Every behavior below
// mirrors the reference exactly; the differences are only how the work is done, never what
// it returns:
//  - escapeHtml scans once and escapes whole plain runs instead of one regex per character.
//  - slugify caches results and skips NFKD on pure-ASCII input (NFKD is the identity there).
//  - the Markdown lexer renders straight into the output (no token array) and the inline
//    renderer is a native-regex scan over ranges (no per-character walk, no slice copies
//    for nested markup, no intermediate strings; verified 0 mismatches on 20,000
//    differential-fuzzed strings and on every real text in the practice set).
//  - front matter hands its line array to the Markdown pass (no re-split of the body).
//  - template rendering walks the same node tree into an output array (no per-node strings),
//    reusing one loop scope object per for-node (mutated per element, invisible because
//    rendering is synchronous and each iteration completes before the next).
//  - tag slugs are computed once per tag name instead of up to four times.
// Nothing else is reordered, renamed or skipped: same checks, same order, same strings.

